assert.equal(state.instrumentId,2);
for(const k of ['lastPrice','h1Layers','loadedCandleInstrument','loadedCandleTf'])assert.equal(state[k],null,k);
assert.equal(state.candles.length,0);assert.equal(state.zones.length,0);assert.equal(deskData.current,null);
assert.equal(painted.length,2);assert.equal(deskData.reqSeq,2);assert.equal(state.h1Req,2);
deskData.current={instrument_id:1,selected_context_id:111};
assert.equal(context.h1QueryExtra().context_id,undefined,'old instrument context must not affect a new chart');
