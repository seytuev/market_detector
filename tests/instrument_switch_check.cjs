const context={state,deskData,Map,hideH1Chrome(){},drawZones(){},renderDeskExtras(){},window:{H1Layers:{loadSettings:()=>({points:'recent'})}}};
vm.createContext(context);
vm.runInContext(source.slice(source.indexOf('function selectAnalysisInstrument('),source.indexOf('// Мост для')),context);
vm.runInContext(source.slice(source.indexOf('function h1QueryExtra('),source.indexOf('function onH1LayersChange(')),context);
