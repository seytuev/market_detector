CATALOG_CODES = tuple(_CATALOG)


class _Params(dict):
    def __missing__(self, key: str) -> str:
        return "—"


def render(code: str, params: dict[str, Any] | None = None) -> dict[str, Any]:
    """Код → заголовок и пояснение. Неизвестный код не подменяется чужим смыслом."""
    raw = dict(params or {})
    spec = _CATALOG.get(code)
    if spec is None:
        return {
            "code": code,
            "headline": "Сообщение не настроено",
            "detail": "",
            "params": raw,
        }
    safe = _Params({k: "—" if v is None else v for k, v in raw.items()})
    headline, detail = spec
    return {
        "code": code,
        "headline": headline.format_map(safe),
        "detail": detail.format_map(safe),
        "params": raw,
    }
