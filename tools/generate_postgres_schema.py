"""Generate native PostgreSQL DDL from the final legacy schema, for review.

Run only when preparing a schema release. PostgreSQL startup never opens SQLite.
"""
from pathlib import Path
import re
import sys

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from app.db import Database


def generate():
    db = Database()
    db.migrate()  # include additions for existing databases
    db._migrate_stabilization()
    tables = db.conn.execute("SELECT name,sql FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' ORDER BY name").fetchall()
    indexes = db.conn.execute("SELECT sql FROM sqlite_master WHERE type='index' AND sql IS NOT NULL ORDER BY name").fetchall()
    out = ["-- Generated by tools/generate_postgres_schema.py. Native schema version 1."]
    constraints = []
    for name, ddl in tables:
        def reference(match):
            constraints.append(f'ALTER TABLE "{name}" ADD CONSTRAINT "fk_{name}_{match[1]}" FOREIGN KEY ("{match[1]}") REFERENCES {match[3]}({match[4]}) {match[5] or ""} DEFERRABLE INITIALLY DEFERRED;')
            return match[1] + " " + match[2]
        ddl = re.sub(r"(\w+)\s+((?:INTEGER|TEXT)\s*(?:(?:NOT NULL|UNIQUE|PRIMARY KEY)\s*)*)REFERENCES\s+(\w+)\s*\((\w+)\)(\s+ON DELETE (?:CASCADE|SET NULL|RESTRICT))?", reference, ddl, flags=re.I)
        ddl = re.sub(r"\bid\s+INTEGER\s+PRIMARY KEY(?:\s+AUTOINCREMENT)?", "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", ddl, flags=re.I)
        ddl = re.sub(r"\bINTEGER\b", "BIGINT", ddl, flags=re.I)
        ddl = re.sub(r"\bREAL\b", "DOUBLE PRECISION", ddl, flags=re.I)
        ddl = re.sub(r"CREATE TABLE\s+(?!IF NOT EXISTS)", "CREATE TABLE IF NOT EXISTS ", ddl, count=1, flags=re.I)
        ddl = re.sub(r"\buser\b", '"user"', ddl)
        out.append(ddl + ";")
    out.extend(r[0] + ";" for r in indexes)
    out.extend(constraints)
    db.close()
    Path(__file__).resolve().parents[1].joinpath("app/schema_postgres.sql").write_text("\n\n".join(out)+"\n", encoding="utf-8")
    print(f"Generated {len(tables)} tables, {len(indexes)} indexes, {len(constraints)} foreign keys")


if __name__ == "__main__":
    generate()
