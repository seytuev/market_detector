assert.equal(context.h1QueryExtra().context_id,222);
context.selectAnalysisInstrument(1);
assert.equal(deskData.current,null);assert.equal(state.h1Req,3,'returning to an instrument invalidates its old in-flight requests');
console.log('Instrument switching clears painted domains and isolates context identity');
