const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const source = fs.readFileSync('app/web/static/app.js', 'utf8');
const painted=[];
const state={instrumentId:1,lastPrice:81000,candles:[{close:81000}],zones:[{id:1}],groups:[{}],h1Layers:{snapshot:{instrument_id:1}},candleReq:1,zoneReq:1,eventReq:1,candidateReq:1,detailReq:0,h1Req:1,candleSeries:{setData:v=>painted.push(['candles',v]),setMarkers:v=>painted.push(['markers',v])}};
const deskData={current:{instrument_id:1,selected_context_id:111},reqSeq:1,pending:{id:1},entryZones:new Map()};
const context={state,deskData,Map,AbortController,hideH1Chrome(){},drawZones(){},renderDeskExtras(){},window:{H1Layers:{loadSettings:()=>({points:'recent'})}}};
vm.createContext(context);
vm.runInContext(source.slice(source.indexOf('function selectAnalysisInstrument('),source.indexOf('// Мост для')),context);
vm.runInContext(source.slice(source.indexOf('function h1QueryExtra('),source.indexOf('function onH1LayersChange(')),context);
context.selectAnalysisInstrument(2);
assert.equal(state.instrumentId,2);
for(const k of ['lastPrice','h1Layers','loadedCandleInstrument','loadedCandleTf'])assert.equal(state[k],null,k);
assert.equal(state.candles.length,0);assert.equal(state.zones.length,0);assert.equal(deskData.current,null);
assert.equal(painted.length,2);assert.equal(deskData.reqSeq,2);assert.equal(state.h1Req,2);
deskData.current={instrument_id:1,selected_context_id:111};
assert.equal(context.h1QueryExtra().context_id,undefined,'old instrument context must not affect a new chart');
deskData.current={instrument_id:2,selected_context_id:222};
assert.equal(context.h1QueryExtra().context_id,222);
vm.runInContext(source.slice(source.indexOf('function analysisApi('),source.indexOf('// Утилиты')),context);
context.api=(_path,options)=>options.signal;
const previousSignal=context.analysisApi('/instrument-2');
assert.equal(previousSignal,state.analysisAbort.signal,'loaders pass the cancellation signal to fetch');
context.selectAnalysisInstrument(1);
assert.equal(previousSignal.aborted,true,'switching cancels the old instrument network requests');
assert.equal(state.analysisAbort.signal.aborted,false,'new instrument has an active request scope');
assert.equal(deskData.current,null);assert.equal(state.h1Req,3,'returning to an instrument invalidates its old in-flight requests');
console.log('Instrument switching clears painted domains and isolates context identity');
let answer;
context.document={activeElement:null,querySelectorAll:()=>[]};
context.$=()=>null;
context.api=()=>new Promise(resolve=>{answer=resolve;});
vm.runInContext(source.slice(source.indexOf('async function loadZoneDetail('),source.indexOf('function showGroupMembers(')),context);
(async()=>{
  const late=context.loadZoneDetail(123,true);
  context.selectAnalysisInstrument(2);
  answer({zone:{id:123,instrument_id:1}});
  await late;
  assert.notEqual(state.selectedZoneId,123,'late zone details must not repopulate a different instrument');
  console.log('Late zone details preserve instrument isolation');
})().catch(error=>{console.error(error);process.exitCode=1;});
